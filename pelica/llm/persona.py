def find_forbidden(text: str) -> list[str]:
    hits = []
    for pattern in FORBIDDEN_PATTERNS:
        m = re.search(pattern, text, re.IGNORECASE)
        if m:
            hits.append(m.group(0))
    return hits


def split_reply_to_bubbles(text: str, max_len: int = 90, max_bubbles: int = 3) -> list[str]:
    """把回复拆成多条「微信气泡」（模拟真人连发）。

    规则：先按空行/换行分段；超长段按句子边界切成 ≤max_len 的气泡；
    过短（<8 字）的气泡与相邻合并避免碎片；超过 max_bubbles 的尾部
    并进最后一条——真人在群里最多连发两三条，连发一串像刷屏。
    """
    text = (text or "").strip()
    if not text:
        return []
    paras = [p.strip() for p in re.split(r"\n+", text) if p.strip()]
    bubbles: list[str] = []
    for para in paras:
        if len(para) <= max_len:
            bubbles.append(para)
            continue
        sents = re.findall(r"[^。！？!?；;]+[。！？!?；;]?", para)
        cur = ""
        for s in sents:
            if cur and len(cur) + len(s) > max_len:
                bubbles.append(cur)
                cur = s
            else:
                cur += s
        if cur:
            bubbles.append(cur)
    # 碎片合并
    merged: list[str] = []
    for b in bubbles:
        if merged and (len(b) < 8 or len(merged[-1]) < 8) and len(merged[-1]) + len(b) <= max_len:
            merged[-1] += b
        else:
            merged.append(b)
    if not merged:
        return [text]
    # 条数硬上限：尾部并进最后一条，不连发一长串
    if len(merged) > max_bubbles:
        head, tail = merged[:max_bubbles - 1], merged[max_bubbles - 1:]
        merged = head + ["".join(tail)]
    return merged


def sanitize_reply(text: str, max_chars: int = 480) -> str | None:
    """清洗 LLM 回复：去 markdown、查机器腔、截断。

    返回 None 表示回复不合格（含机器腔且无法清洗），调用方应换一句。
    """
    if not text or not text.strip():
        return None
    out = text.strip()
    for pattern, repl in _MARKDOWN_PATTERNS:
        out = pattern.sub(repl, out)
    out = re.sub(r"\n{3,}", "\n\n", out).strip()

    if find_forbidden(out):
        return None
    if len(out) > max_chars:
        cut = out[:max_chars]
        for sep in ("。", "！", "？", "\n"):
            pos = cut.rfind(sep)
            if pos > max_chars // 2:
                out = cut[: pos + 1]
                break
        else:
            out = cut + "……"
    return out
